#!/usr/bin/env bash
# setup-claude-code.sh — POSIX equivalent of scripts/setup-claude-code.ps1.
#
# Usage:
#   ./scripts/setup-claude-code.sh                (prints export commands)
#   ./scripts/setup-claude-code.sh --persist      (also writes them to ~/.config/commandcode-go-opencode/claude.env)

set -euo pipefail

persist=0
for arg in "$@"; do
    case "$arg" in
        --persist) persist=1 ;;
    esac
done

declare -A vars=(
    ["ANTHROPIC_BASE_URL"]="http://127.0.0.1:8787"
    ["ANTHROPIC_AUTH_TOKEN"]="proxy-managed"
    ["ANTHROPIC_DEFAULT_SONNET_MODEL"]="deepseek-v4-pro"
    ["ANTHROPIC_DEFAULT_OPUS_MODEL"]="deepseek-v4-pro"
    ["ANTHROPIC_DEFAULT_HAIKU_MODEL"]="deepseek-v4-flash"
)

echo "# Add these to your shell before running 'claude':"
for k in "${!vars[@]}"; do
    v="${vars[$k]}"
    printf 'export %s=%q\n' "$k" "$v"
    if [[ $persist -eq 1 ]]; then
        printf 'export %s=%q\n' "$k" "$v"
    fi
done | sort

if [[ $persist -eq 1 ]]; then
    out="$HOME/.config/commandcode-go-opencode/claude.env"
    {
        echo "# Generated by commandcode-go-opencode on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
        echo "# Source this file from your shell rc:  source $out"
        for k in ANTHROPIC_BASE_URL ANTHROPIC_AUTH_TOKEN ANTHROPIC_DEFAULT_SONNET_MODEL ANTHROPIC_DEFAULT_OPUS_MODEL ANTHROPIC_DEFAULT_HAIKU_MODEL; do
            printf 'export %s=%q\n' "$k" "${vars[$k]}"
        done
    } > "$out"
    chmod 600 "$out"
    echo ""
    echo "Saved to $out — source it from your shell rc to use Claude Code."
fi

echo ""
echo "Then run: claude"
